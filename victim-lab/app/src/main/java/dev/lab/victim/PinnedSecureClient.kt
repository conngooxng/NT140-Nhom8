package dev.lab.victim

/**
 * Thin facade over [TrafficClient.fetchPinnedSecure] for the Task 11
 * interception-vs-pinning scenario.
 *
 * Why a separate class when `TrafficClient` already has the pin logic?
 * `fetchPinnedSecure` requires the caller to supply a pin every time; this
 * class gives the scenario/UI/instrumentation tests a single entry point
 * where the pin's *source* is fixed and documented, so on-device runs can
 * build the client in one line:
 *
 *     PinnedSecureClient().fetchSecure()          // with the shipped lab pin
 *     PinnedSecureClient(pinSha256 = "...")       // with a fresh pin
 *
 * The pin is NOT new cryptography: it is exactly the SPKI-SHA256 pin that
 * `fetchPinnedSecure` consumes (hex 64 chars or base64 44 chars, see
 * TrafficClient.normalizePin). PinnedSecureClient only decides the defaults.
 *
 * Pin derivation (see docs/verify-task-11.md; must be re-run after the lab
 * certificates are regenerated by server/generate_certs.sh):
 *
 *     openssl x509 -in server/certs/secure.lab.test.pem -noout -pubkey \
 *       | openssl pkey -pubin -outform DER \
 *       | openssl dgst -binary -sha256 | base64
 */
class PinnedSecureClient(
    private val trafficClient: TrafficClient = TrafficClient(),
    /** Lab HTTPS endpoint served by server/labserver.py. */
    private val baseUrl: String = DEFAULT_BASE_URL,
    /** SPKI SHA-256 pin; defaults to the lab leaf documented in the README. */
    private val pinSha256: String = DEFAULT_PIN_SHA256,
) {
    /**
     * Fetches `/secure` with the pinned client. Expected outcome in Task 11:
     * SUCCEEDS on the direct/no-VPN baseline toward the real labserver leaf,
     * FAILS with SSLPeerUnverifiedException ("Certificate pinning failure!")
     * when the mitmproxy SOCKS5 path intercepts TLS with a fresh key.
     * The exception propagates to the caller so the on-device scenario can
     * show the app error message as the pin-mismatch evidence.
     */
    suspend fun fetchSecure(): String =
        trafficClient.fetchPinnedSecure(baseUrl, pinSha256)

    /** The active pin, normalized to OkHttp's base64 SPKI form. */
    fun base64Pin(): String = trafficClient.normalizePin(pinSha256)

    companion object {
        const val DEFAULT_BASE_URL = "https://secure.lab.test:8443"

        /**
         * SHA-256 of the SPKI of server/certs/secure.lab.test.pem, hex form.
         * Regenerate with the openssl pipeline in the class doc whenever
         * generate_certs.sh re-issues the leaf (the pin does NOT survive with
         * a fresh key pair).
         */
        const val DEFAULT_PIN_SHA256 =
            "6974ee4e1beed03b5fd734e7c64d58afeadaa7fc407c0d42c477159046732c6b"
    }
}
